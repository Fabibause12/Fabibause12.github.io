FARBEN = {
    ".": (206, 206, 206, 255),
    "w": (255, 255, 255, 255),
    "#": (17, 17, 17, 255),
}

zeilen = RASTER.strip("\n").split("\n")
N = len(zeilen)
for i, z in enumerate(zeilen):
    assert len(z) == N, (i, len(z))

bild = Image.new("RGBA", (N, N))
for y, z in enumerate(zeilen):
    for x, c in enumerate(z):
        bild.putpixel((x, y), FARBEN[c])

ziel = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
ziel.mkdir(parents=True, exist_ok=True)
bild.resize((512, 512), Image.NEAREST).save(ziel / "logo.png")
bild.resize((180, 180), Image.NEAREST).convert("RGB").save(ziel / "icon-180.png")
bild.resize((32, 32), Image.LANCZOS).save(ziel / "icon-32.png")
